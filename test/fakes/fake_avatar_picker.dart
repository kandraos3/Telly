import 'dart:typed_data';

import 'package:telly_app/features/profile/data/avatar_picker.dart';

/// Returns [result] (a "cropped" square) or throws when [fail] is set (FE-608).
class FakeAvatarPicker implements AvatarPicker {
  FakeAvatarPicker([this.result]);
  Uint8List? result;
  bool fail = false;
  int calls = 0;

  @override
  Future<Uint8List?> pickSquareAvatar() async {
    calls++;
    if (fail) throw Exception('permission denied');
    return result;
  }
}

